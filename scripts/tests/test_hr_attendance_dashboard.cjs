const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const source = fs.readFileSync(path.join(__dirname, "../../custom_addons/tp_hr_attendance/static/src/dashboard.js"), "utf8");
const context = {Component: class {}, registry: {category: () => ({add() {}})}, writeStore() {}};
vm.createContext(context);
vm.runInContext(source.replace(/^import .*;$/gm, "").replace("export class", "class") + "\nglobalThis.Dashboard = AttendanceDashboard;", context);
(async () => {
    const dashboard = Object.create(context.Dashboard.prototype);
    dashboard.state = {data: null, month: "", page: 3};
    dashboard.draft = {month: "2026-11"};
    dashboard.load = () => Promise.resolve();
    await dashboard.clear();
    assert.equal(dashboard.state.month, "2026-11");
    dashboard.state.detail_date = "2026-11-01";
    dashboard.state.lock = "locked";
    await dashboard.clearDetail();
    assert.equal(dashboard.state.detail_date, "");
    assert.equal(dashboard.state.lock, "");
    assert.equal(dashboard.state.detail_state, "all");
    dashboard.state.page = 2;
    await dashboard.previousPage();
    assert.equal(dashboard.state.page, 1);
    await dashboard.nextPage();
    assert.equal(dashboard.state.page, 2);
    dashboard.state.search = "Synthetic";
    dashboard.draft.search = "Synthetic";
    await dashboard.removeChip("search");
    assert.equal(dashboard.state.search, "");
    assert.equal(dashboard.draft.search, "");
    delete dashboard.load;
    dashboard.request = 0;
    let rejectOld;
    dashboard.orm = {call: () => new Promise((resolve, reject) => {rejectOld = reject;})};
    const oldRequest = dashboard.load();
    dashboard.orm = {call: () => Promise.resolve({month: "2026-11", page: 1})};
    await dashboard.load();
    rejectOld(new Error("Old failed request"));
    await oldRequest;
    assert.equal(dashboard.state.error, "");
    assert.equal(dashboard.state.data.month, "2026-11");
    console.log("PASS: clear before data, detail/pager handlers, chip removal, stale RPC error");
})().catch(error => { console.error(error); process.exitCode = 1; });
